const BLASTERS = WEAPON_CATALOG.filter((w) => /Blaster/.test(w.type)).map((w) => w.name);

function skillChoice(label: string, options: string[], count = 1): SpeciesTraitChoice {
  return { kind: "skill", label, count, options };
}
function instrumentChoice(count = 1): SpeciesTraitChoice {
  return { kind: "instrument", label: "Instrument", count, options: INSTRUMENTS };
}
function toolChoice(label: string, options: string[], count = 1): SpeciesTraitChoice {
  return { kind: "tool", label, count, options };
}
function weaponChoice(label: string, options: string[], count = 1): SpeciesTraitChoice {
  return { kind: "weapon", label, count, options };
}

